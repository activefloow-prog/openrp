const rules: Array<[RegExp,(match:string,...groups:string[])=>string]> = [
  [/^PAYDAY IN (\\d+)s$/,(m,n)=>`STIPENDIO TRA ${n}s`],
  [/^(\\d+) objects$/,(m,n)=>`${n} oggetti`],
  [/^\\$(\\d[\\d,]*) available$/,(m,n)=>`$${n} disponibili`],
  [/^You own (.+)\\. Use your keys to lock it\\.$/,(m,n)=>`Hai acquistato ${n}. Usa le chiavi per chiudere.`],
  [/^Stored in pocket \\((.+)\\)\\. Open F4 → Pocket to place it\\.$/,(m,n)=>`Raccolto nello zaino (${n}). F4 → Zaino per posarlo.`],
  [/^Picked up (.+)\\.$/,(m,n)=>`Hai raccolto: ${n}.`],
  [/^(.+) bought from your shop\\. \\+\\$(.+)$/,(m,n,amount)=>`${n} ha comprato nel tuo negozio. +$${amount}`]
];
export function translateText(value:string):string {
  const key=value.trim();
  if (!key) return value;
  const translation=dictionary[key];
  if (translation!==undefined) return value.replace(key,translation);
  for(const [pattern,fn] of rules){
    const match=key.match(pattern);
    if(match)return value.replace(key,fn(match[0],...match.slice(1)));
  }
  return value;
}
export function translateInterface(root:Element):void {
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes:Text[]=[];
  while(walker.nextNode())nodes.push(walker.currentNode as Text);
  for(const node of nodes){
    if(node.parentElement?.closest('#chat-lines, #hud-name, #target-title, .resident-link, .score-row, #job-title, #chat-input'))continue;
    const original=node.nodeValue||'';
    const translated=translateText(original);
    if(original!==translated)node.nodeValue=translated;
  }
  for(const el of root.querySelectorAll<HTMLInputElement>('input[placeholder]')){
    const translated=translateText(el.placeholder);
    if(translated!==el.placeholder)el.placeholder=translated;
  }
}
export function installItalianUI(root:Element):void {
  translateInterface(root);
  let updating=false;
  const observer=new MutationObserver(mutations=>{
    if(updating)return;
    updating=true;
    try{
      const targets=new Set<Element>();
      for(const m of mutations){
        const el=m.type==='characterData'?m.target.parentElement:
          m.target.nodeType===Node.ELEMENT_NODE?m.target as Element:null;
        if(el&&root.contains(el))targets.add(el);
      }
      for(const element of targets)translateInterface(element);
    }finally{updating=false;}
  });
  observer.observe(root,{subtree:true,childList:true,characterData:true});
}
